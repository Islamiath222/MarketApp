export function formatNGN(amount: number): string {
  return new Intl.NumberFormat('en-NG', {
    style: 'currency',
    currency: 'NGN',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(amount);
}

export function isMarketOpen(market: Market): boolean {
  const days: (keyof typeof market.operatingHours)[] = [
    'sunday',
    'monday',
    'tuesday',
    'wednesday',
    'thursday',
    'friday',
    'saturday',
  ];
  const now = new Date();
  const dayKey = days[now.getDay()]!;
  const hours = market.operatingHours[dayKey];
  if (!hours) return false;

  const [openH = 0, openM = 0] = hours.open.split(':').map(Number);
  const [closeH = 0, closeM = 0] = hours.close.split(':').map(Number);
  const openMins = openH * 60 + openM;
  const closeMins = closeH * 60 + closeM;
  const nowMins = now.getHours() * 60 + now.getMinutes();
  return nowMins >= openMins && nowMins < closeMins;
}
